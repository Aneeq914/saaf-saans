const listeners = new Set();
let current = readStoredLang();

function readStoredLang() {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (v === 'en' || v === 'ur') return v;
  } catch { /* storage blocked */ }
  return 'en';
}

/** Translate a key, with optional {placeholders}. Falls back to English, then the key. */
export function t(key, vars) {
  let s = STRINGS[current]?.[key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

export function getLang() {
  return current;
}

/** Update every [data-i18n], [data-i18n-placeholder], [data-i18n-aria], [data-i18n-title] element. */
export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}

function applyHtmlAttrs() {
  const html = document.documentElement;
  html.lang = current;
  html.dir = current === 'ur' ? 'rtl' : 'ltr';
}

export function setLang(lang) {
  if (lang !== 'en' && lang !== 'ur') return;
  current = lang;
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* ignore */ }
  applyHtmlAttrs();
  applyTranslations();
  listeners.forEach((cb) => { try { cb(lang); } catch (e) { console.error(e); } });
}

export function onLangChange(cb) {
  listeners.add(cb);
  return () => listeners.delete(cb);
}

/** Apply the stored language to the page once at start-up. */
export function initI18n() {
  applyHtmlAttrs();
  applyTranslations();
}
